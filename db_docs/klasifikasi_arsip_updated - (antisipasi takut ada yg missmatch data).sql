CREATE TABLE master_kategori (
  kategori_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  kode_awal VARCHAR(5) NOT NULL,
  nama_kategori VARCHAR(150) NOT NULL,
  status ENUM('Aktif','Nonaktif') NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (kategori_id),
  UNIQUE KEY uq_kode_awal (kode_awal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE master_kode (
  kode_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  kategori_id INT UNSIGNED NOT NULL,
  kode VARCHAR(20) NOT NULL,
  nama_kelompok TEXT NOT NULL,
  has_sub_kode TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('Aktif','Nonaktif') NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (kode_id),
  UNIQUE KEY uq_kode (kode),
  KEY idx_kategori_id (kategori_id),
  KEY idx_status (status),
  FULLTEXT KEY ftx_nama_kelompok (nama_kelompok)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE master_indeks (
  indeks_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  kode_id INT UNSIGNED NOT NULL,
  nama_indeks VARCHAR(1000) NOT NULL,
  urutan_indeks INT UNSIGNED NOT NULL,
  status ENUM('Aktif','Nonaktif') NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (indeks_id),
  UNIQUE KEY uq_kode_urutan (kode_id, urutan_indeks),
  KEY idx_kode_id (kode_id),
  FULLTEXT KEY ftx_nama_indeks (nama_indeks)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

