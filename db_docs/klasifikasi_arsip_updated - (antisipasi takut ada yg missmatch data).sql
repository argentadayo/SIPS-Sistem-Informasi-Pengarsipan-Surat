  UPDATE master_kode
  SET has_sub_kode = (
    SELECT COUNT(*) > 0 FROM master_indeks
    WHERE kode_id = NEW.kode_id AND status = 'Aktif'
  )
  WHERE kode_id = NEW.kode_id;
END$$
