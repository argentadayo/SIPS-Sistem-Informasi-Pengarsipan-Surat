SELECT
  mk.kode_id,
  mk.kode,
  mk.nama_kelompok,
  mk.has_sub_kode,
  mk.status,
  mkat.kategori_id,
  mkat.kode_awal AS kategori_kode,
  mkat.nama_kategori,
  (SELECT COUNT(*) FROM master_indeks mi
     WHERE mi.kode_id = mk.kode_id AND mi.status = 'Aktif') AS jumlah_indeks,
  mk.created_at,
  mk.updated_at
FROM master_kode mk
JOIN master_kategori mkat ON mkat.kategori_id = mk.kategori_id;

DELIMITER $$
