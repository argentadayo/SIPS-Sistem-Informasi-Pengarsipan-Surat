CREATE PROCEDURE sp_get_kode_by_kategori(IN p_kategori_id INT)
BEGIN
  SELECT * FROM v_master_kode_lengkap
  WHERE (p_kategori_id IS NULL OR kategori_id = p_kategori_id)
    AND status = 'Aktif'
  ORDER BY kode;
END$$
CREATE PROCEDURE sp_get_indeks_by_kode(IN p_kode_id INT)
BEGIN
  SELECT indeks_id, kode_id, nama_indeks, urutan_indeks, status
  FROM master_indeks
  WHERE kode_id = p_kode_id AND status = 'Aktif'
  ORDER BY urutan_indeks;
END$$
CREATE PROCEDURE sp_get_kode_detail_json(IN p_kode_id INT)
BEGIN
  SELECT
    mk.kode_id,
    mk.kode,
    mk.nama_kelompok,
    mk.has_sub_kode,
    mkat.nama_kategori,
    (
      SELECT JSON_ARRAYAGG(
               JSON_OBJECT('indeks_id', mi.indeks_id,
                           'nama_indeks', mi.nama_indeks,
                           'urutan_indeks', mi.urutan_indeks)
             )
      FROM master_indeks mi
      WHERE mi.kode_id = mk.kode_id AND mi.status = 'Aktif'
      ORDER BY mi.urutan_indeks
    ) AS sub_kode
  FROM master_kode mk
  JOIN master_kategori mkat ON mkat.kategori_id = mk.kategori_id
  WHERE mk.kode_id = p_kode_id AND mk.status = 'Aktif';
END$$
CREATE PROCEDURE sp_search_klasifikasi(IN p_keyword VARCHAR(255))
BEGIN
  SELECT DISTINCT mk.kode_id, mk.kode, mk.nama_kelompok, mk.has_sub_kode
  FROM master_kode mk
  LEFT JOIN master_indeks mi ON mi.kode_id = mk.kode_id AND mi.status = 'Aktif'
  WHERE mk.status = 'Aktif'
    AND (
      mk.kode LIKE CONCAT(p_keyword, '%')
      OR MATCH(mk.nama_kelompok) AGAINST (p_keyword IN NATURAL LANGUAGE MODE)
      OR MATCH(mi.nama_indeks) AGAINST (p_keyword IN NATURAL LANGUAGE MODE)
    )
  ORDER BY mk.kode;
END$$
